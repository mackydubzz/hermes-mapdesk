const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
let source=fs.readFileSync(path.join(__dirname,'../desktop/plugin.js'),'utf8').replace(/^import .*?from ['"].*?['"];?\r?\n/gm,'');
source=source.slice(0,source.indexOf('export default'));
const helpers=new Function(source+';return {parseCsvPreview,suggestColumn,boundsForViewport,parseBounds,arcgisName,viewportForGeojson:typeof viewportForGeojson==="function"?viewportForGeojson:null};')();
const {parseCsvPreview:parse,suggestColumn:suggest,viewportForGeojson:fit,boundsForViewport:extent,parseBounds:bounds,arcgisName:sourceName}=helpers;
assert.deepEqual(parse('\uFEFF"Site, name",lat,lon\r\n"A\nB",1,2\r\n').headers,['Site, name','lat','lon']);
assert.equal(parse('name,lat,lon\n"A\nB",1,2').rows[0][0],'A\nB');
assert.equal(parse('id,lat,lon\n001,1,2').rows[0][0],'001');
for(const text of ['a,a\n1,2',',b\n1,2','a,b\n1','a,b\n"unterminated,2','a,b\n"a"bad,2','a,b'])assert.throws(()=>parse(text));
assert.equal(suggest(['LAT','LON'],['latitude','lat']),'LAT');
assert.equal(suggest(['lat','Latitude'],['latitude','lat']),'','Ambiguous columns require explicit choice');
assert.equal(parse('lat,lon\n'+'1,2\n'.repeat(5000)).rows.length,5000);
assert.throws(()=>parse('lat,lon\n'+'1,2\n'.repeat(5001)),/5,000/);
assert.equal(typeof fit,'function','Imported datasets need a geometry-based viewport, not a fixed region');
const point={type:'FeatureCollection',features:[{geometry:{type:'Point',coordinates:[2.35,48.86]}}]};
const view=fit(point,800,600);
assert.equal(view.center[0],2.35);assert.ok(Math.abs(view.center[1]-48.86)<0.000001);assert.equal(view.zoom,13);
const collection={features:[{geometry:{type:'GeometryCollection',geometries:[{type:'LineString',coordinates:[[-0.12,51.5],[2.35,48.86]]},{type:'Point',coordinates:[1,50]}]}}]};
const wide=fit(collection,1000,700),narrow=fit(collection,300,250);
assert.ok(wide.center[0]>-0.12&&wide.center[0]<2.35&&wide.center[1]>48.86&&wide.center[1]<51.5);
assert.ok(narrow.zoom<wide.zoom,'Fit must account for the actual map size');
assert.throws(()=>fit({features:[]},500,500),/geometry/);
assert.deepEqual(extent({center:[0,0],zoom:2},512,512),[-45,-40.9799,45,40.9799]);
const paris=extent({center:[2.35,48.86],zoom:10},800,500);
assert.ok(paris[0]<2.35&&paris[2]>2.35&&paris[1]<48.86&&paris[3]>48.86&&paris[2]-paris[0]<1,'Query envelope must follow the visible map');
assert.deepEqual(extent({center:[179,0],zoom:1},800,500).filter((_,i)=>i%2===0),[38.375,180],'Envelope must not wrap the antimeridian');
assert.deepEqual(bounds(' -1, 50,2 ,52'),[-1,50,2,52]);
for(const text of ['','1,2,3','a,b,c,d','2,50,-1,52','-1,52,2,50','-181,0,0,1','0,0,1,91','1,,2,3'])assert.equal(bounds(text),null,text);
assert.equal(sourceName('https://example.com/arcgis/rest/services/City_Parks/FeatureServer/0'),'City Parks · layer 0');
assert.equal(sourceName('https://example.com/elsewhere'),'ArcGIS layer');
console.log('Import helpers: CSV quoting/BOM/limits/ambiguity, geometry-derived viewport and ArcGIS envelope/name helpers passed');
